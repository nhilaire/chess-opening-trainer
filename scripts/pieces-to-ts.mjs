#!/usr/bin/env node
// Turns the cburnett piece SVGs (assets/pieces/, CC BY-SA 3.0, Colin M.L. Burnett) into a TypeScript module of SVG
// strings drawn with react-native-svg's SvgXml. No dependency: `node scripts/pieces-to-ts.mjs`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'assets', 'pieces');
const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => {
    const xml = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
    return `  ${f.replace('.svg', '')}: ${JSON.stringify(xml)},`;
  });
const out = `// Generated by scripts/pieces-to-ts.mjs from assets/pieces/ - do not edit by hand.
// "cburnett" chess pieces by Colin M.L. Burnett, CC BY-SA 3.0 (credited in the About screen and the README).
export const PIECE_SVGS: Record<string, string> = {
${entries.join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'src', 'ui', 'pieceSvgs.ts'), out);
console.log(`wrote src/ui/pieceSvgs.ts (${entries.length} pieces)`);
