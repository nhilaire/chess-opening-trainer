#!/usr/bin/env node
// One-off conversion of the 3 repertoires of the earlier web app (indented text trees, kept as test fixtures in
// src/__tests__/fixtures/pwa/) into PGN strings embedded in the APK (src/content/embeddedOpenings.ts).
// Format of the source: 2 spaces per level, moves separated by spaces, `[Label]` after a move names it.
// French labels get their accents back. No dependency: `node scripts/convert-pwa-openings.mjs`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = [
  { key: 'd4', file: 'd4-openings.txt', color: 'white' },
  { key: 'scandinavian', file: 'scandinavian.txt', color: 'black' },
  { key: 'd4Black', file: 'slav-black.txt', color: 'black' },
];

const ACCENTS = {
  'Defense Indienne': 'Défense Indienne',
  'Defense Slave': 'Défense Slave',
  'Gambit Dame Accepte': 'Gambit Dame Accepté',
  'Gambit Dame Refuse': 'Gambit Dame Refusé',
  'Gambit Dame Refuse - Variante Bg5': 'Gambit Dame Refusé - Variante Bg5',
  'Systeme Colle': 'Système Colle',
  'Systeme de Londres': 'Système de Londres',
};

// Tokens of one source line: moves, a `[Label]` attaching to the move before it.
function tokens(content) {
  const out = [];
  const re = /\[([^\]]*)\]|(\S+)/g;
  let m;
  while ((m = re.exec(content))) {
    if (m[1] !== undefined) {
      const label = m[1].trim();
      if (out.length) out[out.length - 1].comment = ACCENTS[label] ?? label;
    } else out.push({ san: m[2], children: [] });
  }
  return out;
}

export function parseIndented(text) {
  const roots = [];
  const stack = []; // { indent, node }
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const indent = line.search(/\S/);
    const chain = tokens(line.trim());
    if (!chain.length) continue;
    for (let i = 1; i < chain.length; i++) chain[i - 1].children.push(chain[i]);
    while (stack.length && stack[stack.length - 1].indent >= indent) stack.pop();
    (stack.length ? stack[stack.length - 1].node.children : roots).push(chain[0]);
    stack.push({ indent, node: chain[chain.length - 1] });
  }
  return roots;
}

// PGN movetext of a tree: main line first, alternatives as variations.
function moveText(node, ply, forceNumber) {
  const n = Math.floor(ply / 2) + 1;
  const number = ply % 2 === 0 ? `${n}. ` : forceNumber ? `${n}... ` : '';
  const comment = node.comment ? ` { ${node.comment} }` : '';
  return `${number}${node.san}${comment}`;
}

function writeNodes(nodes, ply, forceNumber) {
  if (!nodes.length) return '';
  const [main, ...alternatives] = nodes;
  let out = moveText(main, ply, forceNumber);
  for (const alt of alternatives) {
    const rest = writeNodes(alt.children, ply + 1, Boolean(alt.comment));
    out += ` (${moveText(alt, ply, true)}${rest ? ` ${rest}` : ''})`;
  }
  const next = writeNodes(main.children, ply + 1, alternatives.length > 0 || Boolean(main.comment));
  return next ? `${out} ${next}` : out;
}

export function toPgn(tree) {
  return `${writeNodes(tree, 0, false)} *`;
}

function main() {
  const entries = SOURCES.map(({ key, file, color }) => {
    const text = fs.readFileSync(path.join(root, 'src', '__tests__', 'fixtures', 'pwa', file), 'utf8');
    return { key, color, pgn: toPgn(parseIndented(text)) };
  });
  const body = entries
    .map((e) => `  {\n    key: '${e.key}',\n    color: '${e.color}',\n    pgn: ${JSON.stringify(e.pgn)},\n  },`)
    .join('\n');
  const out = `// Generated by scripts/convert-pwa-openings.mjs from src/__tests__/fixtures/pwa/ - do not edit by hand.
// The 3 repertoires of the earlier web app, installed at first launch (names in the dictionaries, \`openings.*\`).
import type { Color, EmbeddedKey } from '../game/types';

export const EMBEDDED_OPENINGS: { key: EmbeddedKey; color: Color; pgn: string }[] = [
${body}
];
`;
  fs.mkdirSync(path.join(root, 'src', 'content'), { recursive: true });
  fs.writeFileSync(path.join(root, 'src', 'content', 'embeddedOpenings.ts'), out);
  console.log(`wrote src/content/embeddedOpenings.ts (${entries.map((e) => e.key).join(', ')})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
